//! Full oracle comparison against the committed baselines.
//!
//! Usage:
//!   cargo run --release -p genmsi-core --example oracle -- [--runs N] [--write]
//!
//! `--write` refreshes `docs/oracle-comparison.md` with the measured numbers.

use std::path::{Path, PathBuf};

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let runs = args
        .iter()
        .position(|arg| arg == "--runs")
        .and_then(|index| args.get(index + 1))
        .and_then(|value| value.parse::<usize>().ok())
        .unwrap_or(5);
    let write = args.iter().any(|arg| arg == "--write");

    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let models_dir = root.join("fixtures/models");
    let outputs_dir = root.join("fixtures/outputs");

    let mut models: Vec<PathBuf> = std::fs::read_dir(&models_dir)
        .expect("fixtures/models")
        .map(|entry| entry.expect("entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "gmdl"))
        .collect();
    models.sort();

    let mut comparisons = Vec::new();
    let mut expected_errors = Vec::new();
    for path in &models {
        let stem = path
            .file_stem()
            .expect("file stem")
            .to_string_lossy()
            .to_string();
        let report_path = outputs_dir.join(format!("{}.report.txt", stem.replace(' ', "_")));
        let baseline_text = std::fs::read_to_string(&report_path).unwrap_or_default();
        let baseline = genmsi_core::oracle::parse_baseline_report(&baseline_text);

        match genmsi_format::load(path) {
            Ok(model) => match baseline {
                Ok(baseline) => {
                    let comparison = genmsi_core::oracle::compare_model_text(
                        &stem,
                        &model,
                        &baseline_text,
                        runs,
                    );
                    match comparison {
                        Ok(comparison) => {
                            println!(
                                "{:<45} {:>7} {:>6}/{} {:>6.0}%  {}",
                                stem,
                                genmsi_core::report::plain(comparison.horizon),
                                comparison.matched(),
                                comparison.metrics.len(),
                                comparison.match_ratio() * 100.0,
                                comparison.status()
                            );
                            comparisons.push(comparison);
                        }
                        Err(err) => {
                            println!("{stem:<45} COMPARE ERROR {err}");
                            comparisons.push(genmsi_core::oracle::ModelComparison {
                                model: stem.clone(),
                                has_baseline: true,
                                ran: false,
                                error: Some(err.to_string()),
                                metrics: Vec::new(),
                                horizon: baseline.end_time,
                                runs,
                            });
                        }
                    }
                }
                Err(_) => {
                    // Baseline is one of the five error outputs of the reference
                    // application: the engine must refuse the model too, with the
                    // same class.
                    let error = genmsi_core::compile_model(&model)
                        .err()
                        .map(|err| err.to_string())
                        .unwrap_or_else(|| {
                            "model compiled but the reference application refused it".to_string()
                        });
                    println!("{stem:<45} expected error: {error}");
                    expected_errors.push((stem, error));
                }
            },
            Err(err) => {
                let message = err.to_string();
                println!("{stem:<45} load error: {message}");
                expected_errors.push((stem, message));
            }
        }
    }

    let guide = render_reading_guide(&comparisons);
    let note = format!(
        "Generated by `cargo run --release -p genmsi-core --example oracle -- --runs {runs} --write`.\n\
         This file is generated: to change it, change the generator\n\
         (`crates/genmsi-core/examples/oracle.rs`) and regenerate it. Do not edit it by hand.\n\
         \n\
         The **reference application** is the GenMSI desktop program for Windows; the harness runs\n\
         it under Wine to produce the baselines under `fixtures/outputs/`. This document compares\n\
         the Rust engine against those baselines.\n\
         \n\
         Each model runs to the baseline END_TIME with `{runs}` replications seeded from base 7.\n\
         A metric matches when its relative error is within 20% (counts) or 35% (times and\n\
         occupancies), or when the baseline value lies inside the 95% confidence interval of\n\
         our replication mean. The baselines are single samples of a stochastic model, so the\n\
         rule is deliberately generous; see `docs/DECISIONS.md` D6.\n\
         \n\
         {guide}"
    );
    let mut markdown = genmsi_core::oracle::render_markdown(&comparisons, &note);
    markdown.push_str("\n## Baseline artifacts\n\nThree notes follow: two of them are defects of the reference application, and the\n");
    markdown.push_str("third is a property of a single sample. They are documented instead of forced to\n");
    markdown.push_str("match, and the comparison rule is not relaxed for them.\n");
    markdown.push_str("\n### Queue averages of queues that end empty\n\n");
    markdown.push_str("The reference application prints `AVE.CONT.`, `AVE.TIME` and `AVE.(-0)` as exactly\n");
    markdown.push_str("`0,000` for every queue whose `CONT.` is zero at the end of the run, however much\n");
    markdown.push_str("traffic the queue carried: `Parcial 6-11-23` reports `SISTEMA` with `MAX` 117\n");
    markdown.push_str("and 367 entries and still averages 0. All 76 queue rows of the 20 baselines\n");
    markdown.push_str("follow the rule `CONT. = 0 => averages = 0` without exception, so the three\n");
    markdown.push_str("average metrics of such queues cannot match a working statistician; they are\n");
    markdown.push_str("counted as mismatches here and the affected models (`Parcial 6-11-23`,\n");
    markdown.push_str("`TP10__tp10`, `TP6__Clase 6_2_UltimoCliente`) carry that cost in their ratio.\n");
    markdown.push_str("\n### Truncated `Código GPSS` extractions\n\n");
    markdown.push_str("`fixtures/outputs/<model>.gpss.txt` is meant to hold the GPSS program the\n");
    markdown.push_str("reference application generated. For `Parcial 6-11-23`, `TP10`, `TP3`, `TP4`, `TP5`,\n");
    markdown.push_str("`TP6_2` and `TP8` the extraction captured a fragment of the report instead (a three-\n");
    markdown.push_str("or four-line tail, e.g. the `LOGICSWITCH` table), so those files are not usable as\n");
    markdown.push_str("code. The block table of the corresponding `.report.txt` is the authoritative\n");
    markdown.push_str("expansion for every model: it lists each generated block with its operands and\n");
    markdown.push_str("its entry count.\n");
    markdown.push_str("\n### Single-sample noise on small blocks\n\n");
    markdown.push_str("A baseline is one sample, and the count tolerance of 20% is about two\n");
    markdown.push_str("standard deviations at `n = 50`: a block visited a few dozen times can land\n");
    markdown.push_str("outside it by chance. `ejercicio_4__ejercicio_4` is the remaining case. Its\n");
    markdown.push_str("`Entrada1` `TRANSFER` splits 55/45 and the baseline sent 27 of 59 transactions\n");
    markdown.push_str("to `Salida1` where 32.45 is expected (-1.4 sigma, two-sided p ~ 0.20); that\n");
    markdown.push_str("one draw puts the `ColaInformes` entries and `AVE.CONT.` of the model out of\n");
    markdown.push_str("tolerance while the model still matches. It is not a different rule: 18 of the\n");
    markdown.push_str("18 other baseline rows that isolate one `TRANSFER` branch send the `Prob`\n");
    markdown.push_str("share to `Salida1` (`crates/genmsi-core/tests/transfer_branch.rs`).\n");
    markdown.push_str("\n## Models the reference application refuses\n\n");
    markdown.push_str("These five baselines are error outputs, not reports. The engine must reject\n");
    markdown.push_str("each model with an equivalent error class.\n\n");
    markdown.push_str("| Model | Engine error |\n|---|---|\n");
    for (model, error) in &expected_errors {
        markdown.push_str(&format!(
            "| {model} | {} |\n",
            error.replace('|', "\\|").replace('\n', " ")
        ));
    }
    markdown.push_str("\n### TP9__hack\n\nThe reference application crashes with `Se intentó obtener la linea del fuente de un\nbloque inexistente` (an internal bug while looking up the next block). That bug is **not**\nreplicated: the model has no terminating TERMINATE/CLOCK, so the engine reports the\nmodelling error instead of crashing.\n");

    if write {
        let docs = root.join("docs/oracle-comparison.md");
        std::fs::write(&docs, markdown).expect("write docs/oracle-comparison.md");
        println!("\nwrote {}", docs.display());
    } else {
        println!("\n(pass --write to refresh docs/oracle-comparison.md)");
    }
}

/// The "How to read this document" block: what the columns of the tables mean,
/// and the index of the models the document compares.
fn render_reading_guide(comparisons: &[genmsi_core::oracle::ModelComparison]) -> String {
    let mut guide = String::from(
        "## How to read this document\n\n\
         - **Baseline** and **Horizon** - a baseline is one single run of the reference\n\
         \x20\x20application, committed under `fixtures/outputs/`; its horizon is how far that run\n\
         \x20\x20went (its `END_TIME`), and it is the stop time of our replications.\n\
         - **Runs** - the replications of the engine over that horizon, each with its own\n\
         \x20\x20seed (base 7).\n\
         - **Matched** and **Ratio** - how many of the compared metrics matched, and that\n\
         \x20\x20count as a percentage of the metrics compared.\n\
         - **Match** - whether a metric passed the rule stated above (the tolerance, or the\n\
         \x20\x20baseline inside the 95% confidence interval); `docs/DECISIONS.md` D6 states it.\n\
         - **n/a** - the baseline value is zero, so the relative error does not exist.\n\
         \n",
    );
    guide.push_str(&format!("### The {} models compared\n\n", comparisons.len()));
    for comparison in comparisons {
        guide.push_str(&format!(
            "- [`{}`](#{})\n",
            comparison.model,
            genmsi_core::oracle::heading_anchor(&comparison.model)
        ));
    }
    guide.push_str(
        "\nThe five baselines that are error outputs, not reports, are listed under\n\
         [Models the reference application refuses](#models-the-reference-application-refuses).",
    );
    guide
}
